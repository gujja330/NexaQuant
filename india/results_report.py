# india/results_report.py
"""
Consolidated RESULTS file generator — runs the key backtests and writes everything to
output/AEGIS_RESULTS.md (+ output/AEGIS_RESULTS_headline.csv). One inspectable artifact.

Run: python india/results_report.py
"""
import sys, warnings
from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
warnings.simplefilter("ignore")
from india.arjuna_v2 import backtest, stats
from india.probability_surface import surface
from india.capital_ladder import LADDER, rupees

OUT = ROOT / "output"
ASOF = "2026-06-22"


def main():
    L = [f"# AEGIS — Consolidated Backtest Results ({ASOF})",
         "",
         "All figures computed live from `data/raw/india/` (232 stocks, ~1,358 daily rows, "
         "Dec-2020→Jun-2026, Nifty-200, net of 21bps). **Survivorship-inflated levels — trust the "
         "relative edges, not absolute CAGR.**", ""]

    _, idx = backtest(method="ew")
    champ, _ = backtest(method="hrp", regime="global", topn=15, sector_cap=2, rebal=63)
    champ = champ.dropna(); cs = stats(champ, idx)
    eq = (1 + champ).cumprod()

    # 1 headline
    ns = stats(idx.pct_change().reindex(champ.index).fillna(0), idx)
    L += ["## 1. Champion vs Nifty (Core v2.2: HRP + regime + 15 stk + sector≤2, quarterly)", "",
          "| Metric | AEGIS | Nifty-50 |", "|---|---|---|",
          f"| CAGR | {cs['cagr']:.1f}% | {ns['cagr']:.1f}% |",
          f"| Sharpe | {cs['sharpe']:.2f} | {ns['sharpe']:.2f} |",
          f"| max drawdown | {cs['dd']:.1f}% | {ns['dd']:.1f}% |",
          f"| Calmar | {cs['calmar']:.2f} | {ns['calmar']:.2f} |",
          f"| alpha / beta | {cs['alpha']:+.1f}% / {cs['beta']:.2f} | — |", ""]
    headline = dict(cagr=cs['cagr'], sharpe=cs['sharpe'], dd=cs['dd'], calmar=cs['calmar'])

    # 2 decomposition (regime OFF, isolate construction)
    L += ["## 2. Decomposition — does selection/weighting add value? (regime OFF)", "",
          "| Construction | CAGR | Sharpe | maxDD |", "|---|---|---|---|"]
    for nm, kw in [("EW all-200 (no brains)", dict(method="ew")),
                   ("HRP all-200 (weighting only)", dict(method="hrp")),
                   ("EW selected-15", dict(method="ew", topn=15, sector_cap=2)),
                   ("HRP selected-15", dict(method="hrp", topn=15, sector_cap=2))]:
        s = stats(backtest(regime=False, rebal=63, **kw)[0].dropna(), idx)
        L.append(f"| {nm} | {s['cagr']:.1f}% | {s['sharpe']:.2f} | {s['dd']:.1f}% |")
    L += ["", "*Finding: HRP ≈ EW; selection adds little. The Sharpe edge is the REGIME overlay.*", ""]

    # 3 regime ON vs OFF
    L += ["## 3. Regime overlay ON vs OFF (HRP-15)", "", "| Config | CAGR | Sharpe | maxDD |", "|---|---|---|---|"]
    for nm, reg in [("no regime", False), ("simple regime", "simple"), ("GLOBAL regime", "global")]:
        s = stats(backtest(method="hrp", topn=15, sector_cap=2, rebal=63, regime=reg)[0].dropna(), idx)
        L.append(f"| {nm} | {s['cagr']:.1f}% | {s['sharpe']:.2f} | {s['dd']:.1f}% |")
    L.append("")

    # 4 capital ladder
    L += ["## 4. Capital Ladder (stocks per capital)", "",
          "| Capital | Stocks | CAGR | maxDD |", "|---|---|---|---|"]
    for cap, n in LADDER:
        s = stats(backtest(method="hrp", regime="global", topn=n, sector_cap=2, rebal=63)[0].dropna(), idx)
        L.append(f"| {rupees(cap)} | {n} | {s['cagr']:.1f}% | {s['dd']:.1f}% |")
    L.append("")

    # 5 probability surface
    L += ["## 5. Probability Surface (odds of profit by holding period, on ₹1,00,000)", "",
          "| Hold | P(profit) | typical | bad case | mode |", "|---|---|---|---|---|"]
    for label, v in surface(eq, 100000):
        L.append(f"| {label} | {v['p_pos']:.0f}% | ₹{v['median']:+,.0f} | ₹{v['bad']:+,.0f} | {v['mode']} |")
    L.append("")

    L += ["---", "*Generated by `python india/results_report.py`. Reproducible; "
          "in-sample + survivorship-inflated → forward paper (Q3'26→Q2'27) is the real gate.*"]

    OUT.mkdir(exist_ok=True)
    (OUT / "AEGIS_RESULTS.md").write_text("\n".join(L), encoding="utf-8")
    pd.DataFrame([headline]).to_csv(OUT / "AEGIS_RESULTS_headline.csv", index=False)
    print(f"  results written -> output/AEGIS_RESULTS.md  ({len(L)} lines)")
    print(f"  headline csv     -> output/AEGIS_RESULTS_headline.csv")


if __name__ == "__main__":
    main()
